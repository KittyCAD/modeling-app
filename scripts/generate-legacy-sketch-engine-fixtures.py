"""Render captured engine responses as typed fixtures, sharing identical data."""

import argparse
import json
from dataclasses import dataclass
from pathlib import Path


@dataclass
class Expression:
    source: str


def javascript(value, depth=0):
    """Write literals plus references to other captured literals."""
    if isinstance(value, Expression):
        return value.source
    indentation = "  " * depth
    child_indentation = "  " * (depth + 1)
    if isinstance(value, list):
        items = [child_indentation + javascript(item, depth + 1) for item in value]
        return "[\n" + ",\n".join(items) + "\n" + indentation + "]"
    if isinstance(value, dict):
        items = [
            child_indentation + json.dumps(key) + ": " + javascript(item, depth + 1)
            for key, item in value.items()
        ]
        return "{\n" + ",\n".join(items) + "\n" + indentation + "}"
    return json.dumps(value)


def generate(rows):
    rows.sort(key=lambda row: row["key"])
    results = []
    result_indexes = {}
    paths = []
    planes = []

    # Full-program and partial redraw requests often share the same real result.
    for row in rows:
        serialized = json.dumps(row["result"], sort_keys=True)
        if serialized not in result_indexes:
            result_indexes[serialized] = len(results)
            results.append(row["result"])
        row["result"] = Expression(f"results[{result_indexes[serialized]}]")

    def collect(value):
        if isinstance(value, list):
            for item in value:
                collect(item)
        elif isinstance(value, dict):
            if set(value) == {"range", "nodePath", "pathToNode"}:
                path = {"nodePath": value["nodePath"], "pathToNode": value["pathToNode"]}
                if path not in paths:
                    paths.append(path)
            if value.get("type") == "Plane" and value not in planes:
                planes.append(value)
            for item in value.values():
                collect(item)

    collect(results)
    numeric_type = next(
        value["ty"]
        for result in results
        for value in result["variables"].values()
        if value["type"] == "Number"
    )

    def share_literals(value):
        if isinstance(value, list):
            return [share_literals(item) for item in value]
        if not isinstance(value, dict):
            return value
        if value.get("type") == "Number" and value["ty"] == numeric_type:
            return Expression(f"numeric({json.dumps(value['value'])})")
        if value.get("type") == "Plane":
            return Expression(f"planes[{planes.index(value)}]")
        for index, plane in enumerate(planes):
            if value == dict(plane["value"], type="plane"):
                return Expression(f"surface({index})")
        if set(value) == {"range", "nodePath", "pathToNode"}:
            path = {"nodePath": value["nodePath"], "pathToNode": value["pathToNode"]}
            return Expression(f"codeRef({json.dumps(value['range'])}, {paths.index(path)})")
        if set(value) == {"id", "sourceRange"}:
            return Expression(f"meta({json.dumps(value['id'])}, {json.dumps(value['sourceRange'])})")
        return {key: share_literals(item) for key, item in value.items()}

    header = """// Generated by scripts/generate-legacy-sketch-engine-fixtures.py from normal
// engine execution. These helpers only share literal data; they do not evaluate KCL.
import type { KclValueView } from '@rust/kcl-lib/bindings/KclValueView'
import type { NumericType } from '@rust/kcl-lib/bindings/NumericType'
import type { GeoMetaView } from '@rust/kcl-lib/bindings/GeoMetaView'
import type { SketchSurfaceView } from '@rust/kcl-lib/bindings/SketchSurfaceView'
import type { CodeRef } from '@rust/kcl-lib/bindings/Artifact'
import type { SourceRange } from '@src/lang/wasm'
import type { RecordedSketchEngineResult } from '@src/machines/modelingMachine.legacySketch.runtimeFixtures'

"""
    header += "const paths: Pick<CodeRef, 'nodePath' | 'pathToNode'>[] = " + javascript(paths) + "\n"
    header += "const planes: Extract<KclValueView, { type: 'Plane' }>[] = " + javascript(planes) + "\n"
    header += "const numericType: NumericType = " + javascript(numeric_type) + "\n"
    header += """const numeric = (value: number): Extract<KclValueView, { type: 'Number' }> => ({ type: 'Number', value, ty: numericType })
const surface = (index: number): SketchSurfaceView => ({ type: 'plane', ...planes[index].value })
const codeRef = (range: SourceRange, index: number): CodeRef => ({ range, ...paths[index] })
const meta = (id: string, sourceRange: SourceRange): GeoMetaView => ({ id, sourceRange })
"""
    header += "const results: RecordedSketchEngineResult['result'][] = " + javascript(share_literals(results)) + "\n"
    header += "export const recordedSketchEngineResults: RecordedSketchEngineResult[] = " + javascript(rows) + "\n"
    return header


if __name__ == "__main__":
    repository = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("recording", type=Path)
    parser.add_argument(
        "--output",
        type=Path,
        default=repository / "src/machines/modelingMachine.legacySketch.engineResults.ts",
    )
    args = parser.parse_args()
    args.output.write_text(generate(json.loads(args.recording.read_text())))
