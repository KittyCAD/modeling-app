use std::collections::BTreeMap;

use kittycad_modeling_cmds::format::OutputFormat3d;
use schemars::schema::Schema;
use serde_json::Value;

// Schemars uses oneOf instead of enum when variants have their own documentation.
fn enum_values(schema: Schema) -> Vec<Value> {
    let schema = schema.into_object();
    if let Some(values) = schema.enum_values {
        return values;
    }
    schema
        .subschemas
        .unwrap()
        .one_of
        .unwrap()
        .into_iter()
        .flat_map(enum_values)
        .collect()
}

#[test]
fn export_bindings_export_options() {
    let schema = schemars::schema_for!(OutputFormat3d);
    let formats = schema
        .schema
        .subschemas
        .unwrap()
        .one_of
        .unwrap()
        .into_iter()
        .flat_map(|variant| {
            let properties = variant.into_object().object.unwrap().properties;
            enum_values(properties["type"].clone())
        })
        .collect();
    let mut options = BTreeMap::from([("type", formats)]);
    for (field, name) in [
        ("gltfStorage", "GltfStorage"),
        ("stlStorage", "StlStorage"),
        ("plyStorage", "PlyStorage"),
        ("schema", "StepSchema"),
        ("up", "Axis"),
        ("scale", "UnitLength"),
    ] {
        options.insert(field, enum_values(schema.definitions[name].clone()));
    }

    let config = ts_rs::Config::from_env();
    let out_dir = config.out_dir();
    std::fs::create_dir_all(out_dir).unwrap();
    let json = serde_json::to_string_pretty(&options).unwrap();
    std::fs::write(
        out_dir.join("ExportOptions.ts"),
        format!(
            "// This file was generated by `cargo test -p kcl-lib export_bindings`.\n\
             // Do not edit this file by hand.\n\n\
             export default {json} as const\n"
        ),
    )
    .unwrap();
}
